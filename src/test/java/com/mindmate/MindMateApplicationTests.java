package com.mindmate;

import com.mindmate.dto.ChatResponse;
import com.mindmate.dto.CheckInForm;
import com.mindmate.dto.DashboardStats;
import com.mindmate.dto.GoalForm;
import com.mindmate.dto.GoalProgressStats;
import com.mindmate.entity.CheckIn;
import com.mindmate.service.CheckInService;
import com.mindmate.service.CompanionService;
import com.mindmate.service.GeminiService;
import com.mindmate.service.GoalService;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;

import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest
class MindMateApplicationTests {

    @Autowired
    private CheckInService checkInService;

    @Autowired
    private GeminiService geminiService;

    @Autowired
    private CompanionService companionService;

    @Autowired
    private GoalService goalService;

    @Test
    void contextLoads() {
        assertNotNull(checkInService);
        assertNotNull(geminiService);
        assertNotNull(companionService);
        assertNotNull(goalService);
    }

    @Test
    void testSaveCheckInAndCalculateDashboardStats() {
        CheckInForm form = new CheckInForm();
        form.setMoodScore(4);
        form.setMoodEmoji("🙂");
        form.setMoodLabel("Good");
        form.setStress(5);
        form.setSleep(8);
        form.setWorkload(6);
        form.setEnergy(7);
        form.setConnection(8);
        form.setNotes("JUnit automated test check-in entry.");

        CheckIn saved = checkInService.saveCheckIn(form, null);
        assertNotNull(saved.getId(), "CheckIn ID should be generated by SQLite");
        assertEquals(4, saved.getMoodScore());
        assertEquals("🙂", saved.getMoodEmoji());
        assertEquals("Good", saved.getMoodLabel());
        assertEquals(5, saved.getStress());

        DashboardStats stats = checkInService.getDashboardStats();
        assertTrue(stats.getTotalCount() > 0, "Total check-in count should be greater than zero");
        assertNotNull(stats.getLatestMoodEmoji());
        assertNotNull(stats.getChartPolylinePoints());
        assertFalse(stats.getPersonalizedSuggestions().isEmpty(), "Personalized suggestions must be generated");
    }

    @Test
    void testCrisisSafetyDetection() {
        assertTrue(geminiService.isCrisisInput("I want to kill myself"));
        assertTrue(geminiService.isCrisisInput("I feel suicidal today"));
        assertTrue(geminiService.isCrisisInput("don't want to live anymore"));
        assertFalse(geminiService.isCrisisInput("I am feeling stressed about my exam"));

        ChatResponse crisisResponse = companionService.processUserMessage("test-crisis-conv", "I feel suicidal");
        assertTrue(crisisResponse.isCrisisAlert(), "Crisis alert flag should be true");
        assertTrue(crisisResponse.getReply().contains("Tele-MANAS") || crisisResponse.getReply().contains("988"),
                "Crisis response must include emergency helplines");
    }

    @Test
    void testCompanionEmpatheticReply() {
        ChatResponse response = companionService.processUserMessage("test-demo-conv", "I am stressed about my college exams");
        assertNotNull(response.getReply());
        assertFalse(response.getReply().isBlank());
        assertFalse(response.isCrisisAlert());
        assertTrue(response.getReply().toLowerCase().contains("exam") || response.getReply().toLowerCase().contains("stress")
                || response.getReply().toLowerCase().contains("deadline"));
    }

    @Test
    void testGoalCreationAndToggle() {
        GoalForm form = new GoalForm();
        form.setTitle("Drink 2 glasses of water while revising");
        form.setCategory("Hydration");

        var goal = goalService.createGoal(form, null);
        assertNotNull(goal.getId());
        assertFalse(goal.isCompleted());

        var toggled = goalService.toggleGoal(goal.getId());
        assertTrue(toggled.isPresent());
        assertTrue(toggled.get().isCompleted());

        GoalProgressStats progress = goalService.getProgressStats(null);
        assertTrue(progress.getTotalCount() > 0);
        assertNotNull(progress.getFeedbackMessage());
    }

    @Test
    void testExportCsvAndJson() {
        String csv = checkInService.exportAllAsCsv();
        assertNotNull(csv);
        assertTrue(csv.startsWith("ID,Date,Mood_Score,Mood_Emoji,Mood_Label,Stress,Sleep_Hours"));

        String json = checkInService.exportAllAsJson();
        assertNotNull(json);
        assertTrue(json.contains("MindMate AI"));
    }

    @Test
    void testIbmAiFallbackGracefulOperation() {
        // Even when the Python service is offline, check-in reflection should gracefully return a valid response
        var reflection = geminiService.generateReflection(4, "Good", 5, 8, 5, 7, 7, "Testing IBM fallback resilience");
        assertNotNull(reflection);
        assertNotNull(reflection.getTitle());
        assertNotNull(reflection.getText());
        assertNotNull(reflection.getSignal());
        assertNotNull(reflection.getTipTitle());
        assertNotNull(reflection.getTipBody());
    }
}
